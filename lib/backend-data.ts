export interface APIEndpoint {
  id: string
  title: string
  category: string
  emoji: string
  description: string
  detailedDescription: string
  method: string
  path: string
  requiresAuth: boolean
  type: "endpoint" | "service" | "group"
  allowedRoles?: UserRole[]
  requestBody?: any
  headers?: { key: string; value: string }[]
  responses?: {
    [statusCode: string]: {
      description: string
      schema?: any
      example?: any
    }
  }
  functions?: string[]
  parentId?: string
}

